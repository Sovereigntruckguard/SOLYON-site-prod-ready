export function getInsights(locale) {
  return insightRecords.map((record) => ({
    id: record.id,
    date: record.date,
    ...record[locale],
  }));
}

export function getInsight(locale, slug) {
  const record = insightRecords.find((item) => item[locale].slug === slug);
  if (!record) return null;
  return { id: record.id, date: record.date, ...record[locale] };
}

export function getInsightAlternates(id) {
  const record = insightRecords.find((item) => item.id === id);
  if (!record) return null;
  return {
    en: record.en.slug,
    es: record.es.slug,
  };
}

export function getAllInsightParams() {
  return insightRecords.flatMap((record) => [
    { locale: "en", slug: record.en.slug },
    { locale: "es", slug: record.es.slug },
  ]);
}
